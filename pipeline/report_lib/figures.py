@lru_cache(maxsize=1)
def deq_limitation() -> dict:
    return json.loads(DEQ_LIMITATION_PATH.read_text(encoding="utf-8"))


def deq_limitation_block() -> str:
    """The limitation, its attribution, the mandatory pairing sentence and the credit."""
    return deq_limitation()["rendered"]


# Calibri first, Carlito (metric-compatible with Calibri) where Calibri is not
# installed, DejaVu Sans last because matplotlib always ships it. The committed figures
# are built on Windows, where the family must be Calibri, and `configure` refuses to
# draw them in anything else there. A Linux CI runner falls back to Carlito or DejaVu
# Sans; that is acceptable because figures are excluded from the byte comparison. The
# family name reaches no byte-compared artifact: glyphs are written as paths.
FONT_FAMILIES = ["Calibri", "Carlito", "DejaVu Sans"]
REQUIRED_FAMILY_ON_WINDOWS = "Calibri"


class FontError(RuntimeError):
    pass


def configure() -> str:
    """Set deterministic rcParams. Returns the font family actually used."""
    installed = {f.name for f in font_manager.fontManager.ttflist}
    family = next((name for name in FONT_FAMILIES if name in installed), FONT_FAMILIES[-1])
    if sys.platform == "win32" and family != REQUIRED_FAMILY_ON_WINDOWS:
        raise FontError(
            f"figures resolve to {family!r} on Windows; the committed figures must be "
            f"drawn in {REQUIRED_FAMILY_ON_WINDOWS!r}. Install it or build elsewhere."
        )
    plt.rcdefaults()
    matplotlib.rcParams.update(
        {
            "svg.hashsalt": "genarch",
            "svg.fonttype": "path",
            "font.family": "sans-serif",
            "font.sans-serif": [family, *[f for f in FONT_FAMILIES if f != family]],
            "figure.dpi": 100,
            "savefig.dpi": 300,
            "figure.facecolor": "white",
            "axes.facecolor": "white",
            "savefig.facecolor": "white",
            "axes.edgecolor": palette.ink(),
            "axes.labelcolor": palette.ink(),
            "text.color": palette.ink(),
            "xtick.color": palette.ink(),
            "ytick.color": palette.ink(),
            "axes.grid": True,
            "grid.color": palette.grid(),
            "grid.linewidth": 0.6,
            "axes.axisbelow": True,
            "font.size": 9,
            "axes.titlesize": 11,
            "figure.autolayout": False,
            "path.simplify": False,
        }
    )
    return family


_PNG_STRIP = {b"tEXt", b"zTXt", b"iTXt", b"tIME", b"eXIf"}

# matplotlib opens an SVG path in text mode, so on Windows it writes CRLF.
# CONTEXT.md section 1 requires LF, so the bytes are normalised on the way out.
CRLF = bytes((13, 10))
LF = bytes((10,))


def strip_png_metadata(path: Path) -> None:
    """Drop every textual and time chunk, so two runs give identical bytes."""
    data = path.read_bytes()
    signature, out, offset = data[:8], [data[:8]], 8
    if signature != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"not a PNG: {path}")
    while offset < len(data):
        (length,) = struct.unpack(">I", data[offset : offset + 4])
        chunk_type = data[offset + 4 : offset + 8]
        end = offset + 12 + length
        if chunk_type not in _PNG_STRIP:
            out.append(data[offset:end])
        offset = end
    path.write_bytes(b"".join(out))


def save(fig, out_dir: Path, figure_id: str) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    svg = out_dir / f"{figure_id}.svg"
    png = out_dir / f"{figure_id}.png"
    buffer = io.BytesIO()
    fig.savefig(buffer, format="svg", metadata={"Date": None}, bbox_inches="tight")
    svg.write_bytes(buffer.getvalue().replace(CRLF, LF))
    fig.savefig(
        png,
        format="png",
        dpi=300,
        metadata={"Software": None, "Creation Time": None},
        bbox_inches="tight",
    )
    plt.close(fig)
    strip_png_metadata(png)
    return [svg, png]


