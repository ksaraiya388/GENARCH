def f01_network_timeline(out_dir: Path, spans: list[dict], marks: dict) -> list[Path]:
    """One bar per site code across dates, with the unit moves annotated."""
    fig, ax = plt.subplots(figsize=(9.5, 5.2))
    codes = [s["code"] for s in spans]
    for row, site in enumerate(spans):
        runs = [
            (mdates.date2num(a), mdates.date2num(b) - mdates.date2num(a) + 1)
            for a, b in site["runs"]
        ]
        ax.broken_barh(
            runs,
            (row - 0.32, 0.64),
            facecolors=palette.series()[0],
            edgecolors="none",
        )
        for move in site["unit_moves"]:
            ax.annotate(
                move["label"],
                xy=(mdates.date2num(move["on"]), row),
                # Right of the tick, not centred on it: a unit move falls on the
                # same day as a window edge or a dotted line at two sites, and a
                # centred label sat across that line.
                xytext=(3, 8),
                textcoords="offset points",
                ha="left",
                fontsize=8,
                color=palette.series()[1],
            )
            ax.plot(
                [mdates.date2num(move["on"])],
                [row],
                marker="|",
                markersize=11,
                color=palette.series()[1],
            )

    # The two washes stay light, because neither carries a value. A light fill is only
    # legible if its boundary is, so each is outlined in a colour that clears the
    # data-mark floor, and the smoke window is named inside the axes rather than in a
    # caption below them (GENARCH_RULES.md section 6).
    for start, end, alpha, label in (
        (
            marks["common_start"],
            marks["common_end"],
            0.18,
            "Common window, all six sensors collecting",
        ),
        (
            marks["smoke_start"],
            marks["smoke_end"],
            0.38,
            "Wildfire smoke transport weekend",
        ),
    ):
        ax.axvspan(
            mdates.date2num(start),
            mdates.date2num(end) + 1,
            facecolor=palette.wash(),
            alpha=alpha,
            zorder=0,
            label=label,
        )
        ax.axvspan(
            mdates.date2num(start),
            mdates.date2num(end) + 1,
            facecolor="none",
            edgecolor=palette.wash_edge(),
            linewidth=1.0,
            zorder=1,
        )
    # The smoke label and the two dotted-line labels sit in the foot of the axes,
    # in the rows the third-wave sites leave empty before they start. Placed there,
    # none of them crosses a bar or another line. The smoke label is wrapped to fit
    # between the common window's left edge and the smoke band; the reconfiguration
    # label sits left of its line because the sites to its right start on it.
    foot = len(codes) - 0.48
    ax.annotate(
        SMOKE_WINDOW_LABEL.replace(": ", ":\n", 1).replace(" (", "\n(", 1),
        xy=(mdates.date2num(marks["smoke_start"]), foot),
        xytext=(-3, 0),
        textcoords="offset points",
        ha="right",
        va="bottom",
        fontsize=8,
        linespacing=1.15,
        color=palette.ink(),
        zorder=4,
    )
    for index, (when, text) in enumerate(marks["lines"]):
        ax.axvline(
            mdates.date2num(when), color=palette.ink(), linestyle=":", linewidth=1.1, zorder=3
        )
        last = index == len(marks["lines"]) - 1
        ax.annotate(
            text,
            xy=(mdates.date2num(when), foot),
            xytext=(-3 if last else 3, 0),
            textcoords="offset points",
            rotation=90,
            ha="right" if last else "left",
            va="bottom",
            fontsize=8,
            zorder=4,
        )

    ax.set_yticks(range(len(codes)))
    ax.set_yticklabels(codes)
    ax.invert_yaxis()
    ax.set_ylim(len(codes) - 0.4, -0.8)
    ax.xaxis.set_major_locator(mdates.MonthLocator())
    ax.xaxis.set_major_formatter(mdates.DateFormatter("%b"))
    ax.set_xlabel("2026")
    ax.set_ylabel("Site code")
    ax.set_title("Sensor network coverage by site code")
    ax.grid(axis="y", visible=False)
    ax.legend(loc="lower left", fontsize=8, framealpha=1, edgecolor=palette.grid())
    return save(fig, out_dir, "F01_network_timeline")


