def f04_p98_by_site(out_dir: Path, rows: list[dict]) -> list[Path]:
    """Full-record and common-window 98th percentiles, joined per site code.

    A third series gives the common-window value with the smoke window excluded
    (DECISIONS.md D58), joined to the common-window square by a dotted stem.
    """
    fig, ax = plt.subplots(figsize=(8.2, 5.0))
    primary, secondary = palette.series_styles()
    ordered = sorted(rows, key=lambda r: r["code"])
    positions = list(range(len(ordered)))
    # The smoke-excluded series sits a little right of the other two, on its own dotted
    # stem, so where it falls just below the own-record dot (DC-01) neither the stems
    # nor the markers overlap (audit round 2, M6).
    ex_offset = 0.16
    ex_positions = [pos + ex_offset for pos in positions]
    for pos, row in zip(positions, ordered):
        ax.plot(
            [pos, pos],
            [row["full_p98"], row["common_p98"]],
            color=palette.reference(),
            linewidth=1.4,
            zorder=2,
        )
        ax.plot(
            [pos, pos + ex_offset, pos + ex_offset],
            [row["common_p98"], row["common_p98"], row["exsmoke_p98"]],
            color=palette.reference(),
            linewidth=1.0,
            linestyle=":",
            zorder=2,
        )
    ax.scatter(
        positions,
        [r["full_p98"] for r in ordered],
        s=52,
        marker=primary["marker"],
        color=primary["color"],
        zorder=3,
        label="Own record",
    )
    # Hollow, so an own-record dot that coincides with its common-window square (one
    # site's record lies wholly inside the window) shows through it.
    ax.scatter(
        positions,
        [r["common_p98"] for r in ordered],
        s=70,
        marker=secondary["marker"],
        facecolors="none",
        edgecolors=secondary["color"],
        linewidths=1.6,
        zorder=4,
        label="Common window",
    )
    ax.scatter(
        ex_positions,
        [r["exsmoke_p98"] for r in ordered],
        s=52,
        marker="v",
        color=palette.reference(),
        zorder=4,
        label="Common window, smoke window excluded",
    )
    # Record-day labels sit beside their marker, clear of the stem joining the two
    # markers, which a label above or below a marker would sit on: own-record to the
    # left and common-window to the right, so the two stay apart where a site's two
    # values coincide.
    for pos, row in zip(positions, ordered):
        ax.annotate(
            f"{row['full_days']} d",
            xy=(pos, row["full_p98"]),
            xytext=(-7, 0),
            textcoords="offset points",
            ha="right",
            va="center",
            fontsize=6.8,
            color=primary["color"],
        )
        ax.annotate(
            f"{row['common_days']} d",
            xy=(pos, row["common_p98"]),
            xytext=(7, 0),
            textcoords="offset points",
            ha="left",
            va="center",
            fontsize=6.8,
            color=secondary["color"],
        )
        ax.annotate(
            f"{row['exsmoke_days']} d",
            xy=(pos + ex_offset, row["exsmoke_p98"]),
            xytext=(7, 0),
            textcoords="offset points",
            ha="left",
            va="center",
            fontsize=6.8,
            color=palette.reference(),
        )
    ax.axhline(
        PM25_24H_LEVEL,
        color=palette.reference(),
        linestyle="--",
        linewidth=1.4,
        zorder=1,
    )
    # In the right margin, level with the line, where no stem or marker can cross it.
    ax.annotate(
        STANDARD_LINE_LABEL.replace(": ", ":\n", 1).replace("; ", ";\n", 1),
        xy=(1.0, PM25_24H_LEVEL),
        xycoords=("axes fraction", "data"),
        xytext=(6, 0),
        textcoords="offset points",
        ha="left",
        va="center",
        fontsize=7,
        color=palette.ink(),
        annotation_clip=False,
    )
    # Room beside the outer sites for their record-day labels.
    ax.set_xlim(-0.75, len(positions) - 0.25)
    ax.set_xticks(positions)
    ax.set_xticklabels([r["code"] for r in ordered])
    ax.set_xlabel("Site code")
    ax.set_ylabel("98th percentile of daily averages (µg/m³)")
    ax.set_title("Record length and one smoke weekend move the 98th percentile")
    ax.legend(loc="upper left", fontsize=7.5, framealpha=1, edgecolor=palette.grid())
    fig.tight_layout()
    return save(fig, out_dir, "F04_p98_by_site")


