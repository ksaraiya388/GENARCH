"""Generate site/src/content/deq-limitation.json. Nothing in it is retyped.

    python scripts/gen_deq_limitation.py

The limitation is a verbatim quotation attributed to a state agency, so the only
copy of it in this repository is `DEQ_REPORT_LIMITATION` in
`site/src/content/deq-attribution.ts`, transcribed from the PDF. This script
slices that constant out of the TypeScript source and the pairing sentence and
credit line out of `docs/report-2026/CONTEXT.md` section 3. A transcription error
inside such a quote is not recoverable, so no string below is typed here.

Before writing, the quotation is located in the frozen DEQ report the citation
names. Extracted PDF text drops spaces and splits words at a line-end hyphen, so
both sides are compared after joining "-" + line break and removing every
whitespace character (DECISIONS.md D24).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
ATTRIBUTION_TS = REPO_ROOT / "site" / "src" / "content" / "deq-attribution.ts"
CONTEXT_MD = REPO_ROOT / "docs" / "report-2026" / "CONTEXT.md"
OUT_PATH = REPO_ROOT / "site" / "src" / "content" / "deq-limitation.json"

# The most recent frozen DEQ report whose text carries the quotation, and the page
# it sits on. Both are asserted against the PDF below rather than trusted.
CITED_PDF = REPO_ROOT / "pipeline" / "sources" / "freeze-2026" / "deq_dcamp_weekly_2026-10-09.pdf"
CITED_REPORT_DATE = "2026-10-09"
CITED_PAGE = 2
CITATION = (
    f"Virginia DEQ, Data Center Air Monitoring Project weekly report, "
    f"{CITED_REPORT_DATE}, p. {CITED_PAGE}"
)

PAIRING_PREFIX = "Always pair with: "
CREDIT_PREFIX = "Credit line until DEQ Communications supplies its preferred wording: "

DESCRIPTION = (
    "The DEQ limitation language, its mandatory NAAQS pairing sentence and the credit line. "
    "Generated by scripts/gen_deq_limitation.py: the limitation is sliced out of "
    "DEQ_REPORT_LIMITATION in site/src/content/deq-attribution.ts, which is DEQ's published "
    "weekly-report wording transcribed from the PDF, and the pairing sentence and credit line "
    "out of docs/report-2026/CONTEXT.md section 3. Single source of truth: the pipeline "
    "(pipeline/report_lib/figures.py) and the site both read this file. Nobody retypes the "
    "text. The limitation is a verbatim quotation attributed to Virginia DEQ and must not be "
    "paraphrased, shortened or softened. The pairing sentence must accompany it wherever it "
    "appears."
)
LINT_NOTE = (
    'The pairing sentence contains the word "exceedance" because its function is to deny one. '
    "Automated negation detection was removed from the constraint lint by ruling R1, so this "
    "disclaimer trips its own term and carries a reviewed exemption in "
    "docs/constraint-exemptions.json."
)
APPEARS_IN = [
    "the report summary",
    "every limitations box",
    "every sensor-data figure caption",
]


def normalise(text: str) -> str:
    """The D24 matching rule: join "-" + line break, then drop all whitespace."""
    return re.sub(r"\s+", "", re.sub(r"-(?:\r\n|\r|\n)", "", text))


def read_limitation() -> str:
    source = ATTRIBUTION_TS.read_text(encoding="utf-8")
    match = re.search(r"export const DEQ_REPORT_LIMITATION = `(.*?)`;", source, re.S)
    if match is None:
        raise SystemExit(f"DEQ_REPORT_LIMITATION not found in {ATTRIBUTION_TS}")
    return match.group(1)


def read_context_lines() -> tuple[str, str]:
    pairing = credit = None
    for line in CONTEXT_MD.read_text(encoding="utf-8").splitlines():
        if line.startswith(PAIRING_PREFIX):
            pairing = line.removeprefix(PAIRING_PREFIX)
        elif line.startswith(CREDIT_PREFIX):
            credit = line.removeprefix(CREDIT_PREFIX).strip().strip('"')
    if pairing is None or credit is None:
        raise SystemExit(f"could not slice the pairing sentence and credit line from {CONTEXT_MD}")
    return pairing, credit


def assert_quote_is_in_the_cited_report(limitation: str) -> None:
    try:
        import pdfplumber
    except ModuleNotFoundError:
        raise SystemExit(
            "pdfplumber is needed to locate the quotation in the cited report; "
            "install it or run this script where it is available"
        ) from None
    if not CITED_PDF.is_file():
        raise SystemExit(f"cited report is missing: {CITED_PDF}")
    needle = normalise(limitation)
    with pdfplumber.open(str(CITED_PDF)) as pdf:
        if not 1 <= CITED_PAGE <= len(pdf.pages):
            raise SystemExit(f"{CITED_PDF.name} has no page {CITED_PAGE}")
        page_text = pdf.pages[CITED_PAGE - 1].extract_text() or ""
    if needle not in normalise(page_text):
        raise SystemExit(
            f"the quotation is not on p. {CITED_PAGE} of {CITED_PDF.name} under the D24 "
            "matching rule; nothing written"
        )
    print(f"quotation located: {CITED_PDF.name}, p. {CITED_PAGE}")


def main() -> int:
    limitation = read_limitation()
    pairing, credit = read_context_lines()
    assert_quote_is_in_the_cited_report(limitation)

    document = {
        "appears_in": APPEARS_IN,
        "citation": CITATION,
        "credit": credit,
        "description": DESCRIPTION,
        "generated_by": "scripts/gen_deq_limitation.py",
        "limitation": limitation,
        "lint_note": LINT_NOTE,
        "pairing": pairing,
        "rendered": f"{limitation} ({CITATION}) {pairing} {credit}",
        "source": (
            "site/src/content/deq-attribution.ts DEQ_REPORT_LIMITATION (the limitation); "
            "docs/report-2026/CONTEXT.md section 3 (the pairing sentence and the credit line)"
        ),
    }
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(document, handle, ensure_ascii=False, indent=2, sort_keys=True)
        handle.write("\n")
    print(f"wrote {OUT_PATH.relative_to(REPO_ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
