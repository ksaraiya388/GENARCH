#!/usr/bin/env python3
"""Append the ancestry module's AUDIT.md entry: traits matched, and the method comparison.

    python scripts/audit_append_ancestry.py --report-dir data/reports/2026

Two things the module owes AUDIT.md, both generated rather than typed, because
CONTEXT.md section 8 forbids a hand-typed decimal anywhere a report number
appears:

* every distinct MAPPED_TRAIT the ontology-ID selection matched, for review;
* the share-by-share comparison between what /ancestry-equity shows and what the
  report computes, with the difference on each row.

AUDIT.md is append-only (DECISIONS.md D23): this writes a dated entry at the end
and edits nothing above it.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AUDIT = ROOT / "docs" / "report-2026" / "AUDIT.md"
EXTRACT_MANIFEST = ROOT / "pipeline" / "sources" / "gwas-catalog" / "extract_manifest.json"
PAGE_CSV = ROOT / "pipeline" / "sources" / "gwas_ancestry_breakdown.csv"
FIGURES_TS = ROOT / "site" / "src" / "lib" / "figures.ts"

# The page's "Asian" bar has no single counterpart in the catalog's vocabulary,
# which itemises five Asian categories. To put a number beside it the five are
# summed, and the mapping is stated on the row rather than left implicit.
ASIAN_KEYS = (
    "east_asian",
    "south_asian",
    "south_east_asian",
    "central_asian",
    "asian_unspecified",
)
PAGE_TO_CATALOG = {
    "European": (("european",), "the catalog's single European category"),
    "Asian": (
        ASIAN_KEYS,
        "the sum of the catalog's five Asian categories (East, South, South East, "
        "Central, Asian unspecified), because the dashboard publishes one undivided "
        "Asian bar and the catalog publishes no such category",
    ),
}


class Stop(Exception):
    pass


def snapshot_as_of() -> str:
    """The `as_of` value the live figure is pinned to, read from the site source."""
    text = FIGURES_TS.read_text(encoding="utf-8")
    match = re.search(r'SNAPSHOT_AS_OF\s*=\s*"([^"]+)"', text)
    if not match:
        raise Stop(f"could not read SNAPSHOT_AS_OF from {FIGURES_TS}")
    return match.group(1)


def page_values(as_of: str) -> dict[str, float]:
    with open(PAGE_CSV, encoding="utf-8", newline="") as handle:
        rows = [r for r in csv.DictReader(handle) if r["as_of"] == as_of]
    if not rows:
        raise Stop(f"no rows in {PAGE_CSV.name} for as_of {as_of}")
    return {r["ancestry_group"]: float(r["gwas_participant_pct"]) for r in rows}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report-dir", default="data/reports/2026")
    args = parser.parse_args(argv)
    try:
        report_dir = (ROOT / args.report_dir).resolve()
        numbers_path = report_dir / "numbers.json"
        if not numbers_path.is_file():
            raise Stop(f"missing {numbers_path}; run the report first")
        numbers = json.loads(numbers_path.read_text(encoding="utf-8"))
        if not EXTRACT_MANIFEST.is_file():
            raise Stop(f"missing {EXTRACT_MANIFEST}")
        extract = json.loads(EXTRACT_MANIFEST.read_text(encoding="utf-8"))

        def value(key: str):
            if key not in numbers:
                raise Stop(f"numbers.json has no key {key}")
            return numbers[key]["value"]

        release = extract["release_date"]
        as_of = snapshot_as_of()
        page = page_values(as_of)

        lines: list[str] = []
        lines.append("")
        lines.append(
            f"{date.today().isoformat()}: the ancestry-composition module's two review "
            "artefacts, generated by scripts/audit_append_ancestry.py from "
            "numbers.json and the extract manifest. No figure below is typed by hand."
        )
        lines.append("")

        # ---- matched traits
        traits = extract["mapped_traits_matched"]
        unmatched = extract["asthma_term_ids_unmatched"]
        matched_ids = extract["asthma_term_ids_matched"]
        lines.append(
            f"Distinct MAPPED_TRAIT values matched by the {len(extract['asthma_term_ids'])} "
            f"asthma ontology IDs, GWAS Catalog release {release}. Selection is by the "
            "last path segment of each IRI in MAPPED_TRAIT_URI; no trait name is matched "
            "as free text, so the names below are the output of the selection and never "
            "an input to it. "
            f"{extract['association_rows_kept']} of {extract['association_rows_scanned']} "
            f"association rows were kept, across {extract['study_accessions']} study "
            "accessions."
        )
        lines.append("")
        lines.append("| MAPPED_TRAIT | Association rows |")
        lines.append("|---|---|")
        for label, count in sorted(traits.items(), key=lambda kv: (-kv[1], kv[0])):
            lines.append(f"| {label} | {count} |")
        lines.append("")
        lines.append("| Ontology ID | Association rows |")
        lines.append("|---|---|")
        for term_id, count in sorted(matched_ids.items(), key=lambda kv: (-kv[1], kv[0])):
            lines.append(f"| {term_id} | {count} |")
        lines.append("")
        if unmatched:
            lines.append(
                f"{len(unmatched)} of the term IDs matched no association in this "
                "release and are listed so the set stays reviewable rather than looking "
                f"complete: {', '.join(unmatched)}. An ID matching nothing is kept in "
                "the lookup: it is a term the ontology places under asthma, and its "
                "absence here is a fact about this release's curation, not a reason to "
                "narrow the selection."
            )
        else:
            lines.append("Every term ID matched at least one association in this release.")
        lines.append("")

        # ---- the comparison
        lines.append(
            "Method comparison between the live page and the report, owed by the step 0 "
            "entry of 2026-11-03 above. The "
            "page value is the GWAS Diversity Monitor transcription in "
            f"pipeline/sources/gwas_ancestry_breakdown.csv, as_of {as_of}, which "
            "site/src/lib/figures.ts pins through SNAPSHOT_AS_OF. The catalog value is "
            f"recomputed here from GWAS Catalog release {release} over asthma studies "
            "only, counting initial-stage discovery individuals."
        )
        lines.append("")
        lines.append(
            "| Category as the page shows it | Page value (percent) | "
            "Catalog-derived (percent) | Difference (percentage points) | "
            "What the catalog value sums |"
        )
        lines.append("|---|---|---|---|---|")
        for label in sorted(page):
            if label not in PAGE_TO_CATALOG:
                lines.append(
                    f"| {label} | {page[label]} | not computed | not computed | "
                    "no counterpart in this release's asthma studies |"
                )
                continue
            keys, note = PAGE_TO_CATALOG[label]
            total = sum(value(f"ancestry.discovery.{k}.share") for k in keys if
                        f"ancestry.discovery.{k}.share" in numbers)
            lines.append(
                f"| {label} | {page[label]} | {round(total, 2)} | "
                f"{round(total - page[label], 2)} | {note} |"
            )
        lines.append("")
        lines.append(
            "The difference on each row is not an error in either figure. The two "
            "quantities have different denominators: the page counts participants in "
            "every GWAS of every trait as a third-party dashboard tallied them in "
            f"{as_of}, and the report counts individuals in the initial-stage discovery "
            "samples of asthma studies in one dated catalog release. A row's difference "
            "measures the distance between those two definitions and nothing else. "
            "Neither value can be substituted for the other, and the report states this "
            "wherever it gives a share (numbers.json key ancestry.method_divergence, "
            "repeated in the T10 caption)."
        )
        lines.append("")
        lines.append(
            "Resolution, and what is still open. The report and the page now have one "
            "method each for one clearly labelled quantity, and the report names the "
            "page's source and denominator wherever it states its own share, so the two "
            "cannot be read as two values of a single quantity. /ancestry-equity is "
            "unchanged, per the ruling on this work: it reads the 2023 ACS file and the "
            "dashboard transcription, and rewriting a public page's sourcing was not in "
            "scope here. What stays open is the page side: the all-trait dashboard bars "
            "carry no denominator on the page itself, so a reader who sees only the page "
            "still cannot tell what population the share describes. Relabelling those "
            "bars, or replacing them with the recomputed asthma figure, is the remaining "
            "work and is not done."
        )
        lines.append("")

        # ---- ACS release divergence
        acs_release = value("ancestry.acs.release")
        lines.append(
            f"ACS release divergence, open item. The report's T12 and the F06 ACS panel "
            f"read the {acs_release} ACS 5-year release, retrieved for this module into "
            f"pipeline/sources/cross_ancestry/acs_loudoun_{acs_release}_*.json. The live "
            "page /ancestry-equity reads the 2023 release in "
            "pipeline/sources/cross_ancestry/acs_loudoun_2023.json and is unchanged, so "
            "the report and the page state county counts from two different vintages. "
            "Nothing is wrong with either number on its own terms and both name their "
            "vintage, but a reader comparing the two surfaces will find different totals "
            "for the same county. Moving the page to the newer release, or stating the "
            "vintage more prominently on it, is open."
        )
        lines.append("")

        with open(AUDIT, "a", encoding="utf-8", newline="\n") as handle:
            handle.write("\n".join(lines) + "\n")

        print(f"appended {len(lines)} lines to {AUDIT.relative_to(ROOT).as_posix()}")
        print(f"  {len(traits)} distinct MAPPED_TRAIT values, {len(unmatched)} unmatched IDs")
        return 0
    except Stop as exc:
        print(f"STOP: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
